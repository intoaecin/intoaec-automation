Before({ tags: '@cost-catalog or @cost-catalog-tc' }, async function ({ pickle }) {
  const tags = (pickle.tags || []).map((t) => t.name.replace(/^@/, ''));
  const tc = tags.find((t) => /^TC\d+$/i.test(t));
  if (tc && COST_CATALOG_TEST_CASE_LOG[tc.toUpperCase()]) {
    console.log(`\n>>> ${COST_CATALOG_TEST_CASE_LOG[tc.toUpperCase()]}\n`);
  }
});

function getCostCatalogPage(world) {
  if (!world.costCatalogPage || world.costCatalogPage.page !== world.page) {
    world.costCatalogPage = new CostCatalogPage(world.page);
  }
  return world.costCatalogPage;
}

