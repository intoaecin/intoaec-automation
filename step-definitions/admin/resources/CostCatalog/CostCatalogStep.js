When(
  'I enter Cost Catalog material {int} details with name {string}, unit {string}, brand {string}, and cost {string}',
  { timeout: 180000 },
  async function (index, name, unit, brand, cost) {
    await this.ensureLivePage();
    const costCatalog = getCostCatalogPage(this);
    try {
      await costCatalog.enterMaterialDetails(index, name, unit, brand, cost);
    } catch (err) {
      const msg = String(err?.message || err);
      if (Number(index) > 1 && /closed|Target page|browser has been closed/i.test(msg)) {
        console.log('[CostCatalog] Page closed after material 1 save — recovering session for material 2');
        await this.ensureLivePage();
        const recovered = getCostCatalogPage(this);
        await recovered.selectCostCatalog();
        await recovered.selectMaterialsTab();
        await recovered.clickAddItems();
        await recovered.selectItemTypeMaterials();
        await recovered.enterMaterialDetails(1, name, unit, brand, cost);
        return;
      }
      throw err;
    }
  }
);

